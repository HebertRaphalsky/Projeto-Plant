plt.show()

# Calcula a curva ROC e a área sob a curva (AUC).
# Calcula e visualiza ROC/AUC para avaliar a separação entre as classes.
# CÉLULA 25 — ROC SVM
y_test_bin = label_binarize(y_test, classes=np.arange(NUM_CLASSES))
y_prob_svm = svm_pca.predict_proba(X_test_pca)

plt.figure(figsize=(10,8))
for i in range(NUM_CLASSES):
    fpr, tpr, _ = roc_curve(y_test_bin[:, i], y_prob_svm[:, i])
    roc_auc = auc(fpr, tpr)
    plt.plot(fpr, tpr, label=f"{nomes_plot[i]} (AUC={roc_auc:.2f})")

plt.plot([0,1], [0,1], linestyle="--", label="Aleatório")
plt.title("Curva ROC — SVM")
plt.xlabel("Taxa de Falsos Positivos")
plt.ylabel("Taxa de Verdadeiros Positivos")
plt.legend(bbox_to_anchor=(1.05,1), loc="upper left")
